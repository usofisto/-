#include "biom.h"
#include <iostream>
#include <cstdlib>
#include <ctime>
#include <algorithm> // для использования std::min

// РЕАЛИЗАЦИЯ БИОМА: ЗЕЛЕНАЯ ПОЛЯНА (Meadow Biome)
// Здесь игрок может свободно перемещаться, собирать травы или драться.
void enterMeadowBiome(Player& player) {
    // Приветственное описание локации при входе
    std::cout << "\n----------------------------------------------------\n";
    std::cout << "Вы шагнули на мягкую траву Зеленой Поляны...\n";
    std::cout << "Вокруг колышется сочная зелень, цветут одуванчики и ромашки.\n";
    std::cout << "Где-то неподалеку слышно тихое урчание слизи.\n";
    std::cout << "----------------------------------------------------\n";

    // Убедимся, что генератор случайных чисел инициализирован один раз
    static bool randInitialized = false;
    if (!randInitialized) {
        std::srand(static_cast<unsigned int>(std::time(nullptr)));
        randInitialized = true;
    }

    bool exploring = true;
    while (exploring && player.isAlive) {
        std::cout << "\n[ПОЛЯНА] Выберите действие:\n";
        std::cout << "1. Осмотреться вокруг\n";
        std::cout << "2. Собирать целебные травы и цветы\n";
        std::cout << "3. Искать приключения (найти существо)\n";
        std::cout << "4. Показать статус персонажа\n";
        std::cout << "5. Вернуться в лагерь (выйти из биома)\n";
        std::cout << "Ваш выбор (1-5): ";

        int actionChoice = 0;
        std::cin >> actionChoice;

        // Валидация ввода (чтобы избежать бесконечного цикла при вводе букв)
        if (std::cin.fail()) {
            std::cin.clear();
            std::cin.ignore(32767, '\n');
            std::cout << "Пожалуйста, введите число от 1 до 5!\n";
            continue;
        }

        switch (actionChoice) {
            case 1: {
                // Обычный осмотр местности
                std::cout << "\n[ОСМОТР] Вы видите бескрайнее зеленое поле. На горизонте возвышаются темные горы.\n";
                std::cout << "Под ногами ползают безобидные жучки. Это место кажется мирным, но расслабляться не стоит.\n";
                break;
            }
            case 2: {
                // Сбор ресурсов с разным шансом (трава, цветок или ничего)
                std::cout << "\n[СБОР] Вы начали аккуратно прочесывать траву...\n";
                int rnd = std::rand() % 100;

                if (rnd < 40) {
                    // 40% шанс найти лечебную траву
                    int healAmount = 15 + (std::rand() % 11); // 15-25 HP
                    player.health = std::min(player.maxHealth, player.health + healAmount);
                    std::cout << "Вы нашли лечебную подорожник-траву! Здоровье восстановлено на " << healAmount << " HP.\n";
                } 
                else if (rnd < 75) {
                    // 35% шанс найти золотой цветок
                    int goldAmount = 10 + (std::rand() % 16); // 10-25 золота
                    player.gold += goldAmount;
                    std::cout << "О! Вы нашли редкий Золотоцвет! Вы бережно сорвали его (+" << goldAmount << " золота).\n";
                } 
                else {
                    // 25% шанс ничего не найти
                    std::cout << "К сожалению, вы не нашли ничего полезного, кроме обычной крапивы.\n";
                }
                break;
            }
            case 3: {
                // Поиск приключений (случайное существо или событие)
                std::cout << "\n[ПОИСК] Вы раздвигаете руками высокую траву...\n";
                int encounter = std::rand() % 100;

                if (encounter < 35) {
                    // 35% шанс пустой поляны
                    std::cout << "Вы никого не встретили. Только испуганный заяц пронесся мимо.\n";
                } 
                else {
                    // Встреча с легендарной Слизью
                    std::cout << "\n!!! ВСТРЕЧА !!!\n";
                    std::cout << "Перед вами прыгает полупрозрачная, желеобразная Зеленая Слизь!\n";
                    std::cout << "Она не нападает сразу, а с любопытством перекатывается сбоку на бок.\n";
                    
                    bool inEncounter = true;
                    while (inEncounter && player.isAlive) {
                        std::cout << "\nЧто вы предпримете?\n";
                        std::cout << "1. Попытаться подружиться (посадить слизь на голову как шапку)\n";
                        std::cout << "2. Атаковать и уничтожить её\n";
                        std::cout << "3. Попытаться аккуратно сбежать\n";
                        std::cout << "Ваш выбор (1-3): ";

                        int slimeChoice = 0;
                        std::cin >> slimeChoice;

                        if (std::cin.fail()) {
                            std::cin.clear();
                            std::cin.ignore(32767, '\n');
                            std::cout << "Некорректный ввод. Выберите 1, 2 или 3.\n";
                            continue;
                        }

                        if (slimeChoice == 1) {
                            // Прикол со слизью: шанс раскачаться или умереть
                            std::cout << "\nВы медленно опускаетесь на корточки и маните слизь к себе...\n";
                            std::cout << "Слизь делает огромный прыжок прямо на вашу голову!\n";

                            int fatalityChance = std::rand() % 100;
                            if (fatalityChance < 20) {
                                // 20% шанс мгновенной гибели
                                std::cout << "\n[СМЕРТЕЛЬНЫЙ ПРИКОЛ] О НЕТ! Слизь оказалась слишком жидкой и липкой!\n";
                                std::cout << "Она полностью залепила вам лицо, проникла в рот и нос, лишив кислорода.\n";
                                std::cout << "Вы судорожно пытаетесь сорвать её, но она соскальзывает обратно...\n";
                                std::cout << "Ваше зрение темнеет. Вы задохнулись и погибли.\n";
                                
                                player.health = 0;
                                player.isAlive = false;
                            } 
                            else {
                                // 80% шанс получить постоянный бафф характеристик
                                int dmgGain = 3 + (std::rand() % 5);   // +3..+7 к урону
                                int hpGain = 10 + (std::rand() % 11);  // +10..+20 к макс. здоровью
                                player.damage += dmgGain;
                                player.maxHealth += hpGain;
                                player.health = std::min(player.maxHealth, player.health + hpGain);

                                std::cout << "\n[УДАЧА] Невероятно! Слизь забавно устроилась на вашей макушке как живая шляпа.\n";
                                std::cout << "Она начинает выделять приятное тепло, стимулирующее ваши мышцы и разум!\n";
                                std::cout << "Вы чувствуете себя намного сильнее!\n";
                                std::cout << "-> Максимальный урон увеличен на +" << dmgGain << " (Текущий: " << player.damage << ")\n";
                                std::cout << "-> Максимальное здоровье увеличено на +" << hpGain << " (Текущее: " << player.maxHealth << ")\n";
                                std::cout << "Слизь растаяла, оставив приятный шлейф магической энергии.\n";
                            }
                            inEncounter = false;
                        } 
                        else if (slimeChoice == 2) {
                            // Обычная битва со слизью
                            std::cout << "\n[БОЙ] Вы обнажаете оружие и наносите резкий удар!\n";
                            std::cout << "Вы разрываете слизь на мелкие кусочки, нанеся " << player.damage << " урона.\n";
                            
                            int goldLoot = 15 + (std::rand() % 16); // 15-30 золота
                            player.gold += goldLoot;
                            std::cout << "Слизь повержена! В её останках вы находите растворенные монеты (+" << goldLoot << " золота).\n";
                            inEncounter = false;
                        } 
                        else if (slimeChoice == 3) {
                            // Безопасный побег
                            std::cout << "\nВы медленно пятились назад и успешно скрылись в высокой траве.\n";
                            inEncounter = false;
                        } 
                        else {
                            std::cout << "Неверный выбор. Пожалуйста, введите число от 1 до 3.\n";
                        }
                    }
                }
                break;
            }
            case 4: {
                // Карточка персонажа в любой момент времени
                std::cout << "\n--------------------------------------------\n";
                std::cout << " СТАТУС ПЕРСОНАЖА:\n";
                std::cout << " Имя: " << player.name << "\n";
                std::cout << " Класс: " << player.className << "\n";
                std::cout << " Здоровье: " << player.health << "/" << player.maxHealth << " HP\n";
                std::cout << " Урон (сила атаки): " << player.damage << "\n";
                std::cout << " Золото: " << player.gold << "\n";
                std::cout << "--------------------------------------------\n";
                break;
            }
            case 5: {
                // Возврат в главное меню игры
                std::cout << "\nВы разворачиваетесь и возвращаетесь в безопасный лагерь...\n";
                exploring = false;
                break;
            }
            default:
                std::cout << "Некорректный выбор. Введите число от 1 до 5.\n";
                break;
        }
    }

    // Сообщение о гибели, если игрока задушила слизь
    if (!player.isAlive) {
        std::cout << "\n--------------------------------------------\n";
        std::cout << "             ИГРА ОКОНЧЕНА                  \n";
        std::cout << " Ваше приключение на Поляне закончилось смертью.\n";
        std::cout << "--------------------------------------------\n";
    }
}
